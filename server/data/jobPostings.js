// Helper for aggregate market demand statistics
export function getAggregateMarketDemand() {
  const counts = {};
  OFF_CAMPUS_JOB_POSTINGS.forEach(job => {
    job.requiredSkills.forEach(skill => {
      counts[skill.name] = (counts[skill.name] || 0) + (skill.mandatory ? 2 : 1);
    });
  });

  const totalJobs = OFF_CAMPUS_JOB_POSTINGS.length;
  return Object.entries(counts)
    .map(([name, score]) => ({
      name,
      demandFrequency: Math.min(99, Math.round((score / (totalJobs * 1.5)) * 100)),
      jobCount: OFF_CAMPUS_JOB_POSTINGS.filter(j => j.requiredSkills.some(s => s.name === name)).length
    }))
    .sort((a, b) => b.demandFrequency - a.demandFrequency);
}
